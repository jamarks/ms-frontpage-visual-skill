#!/usr/bin/env python3
"""Build a site-wide index for the kit's Search Form, FrontPage-style ("Number of documents found").

  python3 build_search_index.py SITE_DIR [--out theme/search-index.js] [--exclude a.html,b.html]

Frameset shells are skipped automatically; anything inside class="fp-noindex" or data-fp-noindex
(search tips, nav) is left out.

Splits every page into sections at <h1>-<h3> (linking to the heading's id when it has one), skips
shared borders/nav/scripts, and writes `window.FP_SEARCH_INDEX = [...]` to a .js file. Include it
before fp-kit.js on the search page and use <form data-fp-search="site" ...>. Works from file:// because
it is a plain script, not a fetch(). Re-run it after editing content. Stdlib only.
"""
import json
import os
import re
import sys
from html.parser import HTMLParser

SKIP_TAGS = {'script', 'style', 'nav', 'noscript', 'form', 'select'}
SKIP_CLASSES = {'fp-noindex', 'fp-border-top', 'fp-border-bottom', 'fp-side', 'fp-navbar', 'fp-navbar-v', 'fp-textnav', 'fp-search-results'}
VOID = {'area', 'base', 'br', 'col', 'embed', 'hr', 'img', 'input', 'link', 'meta', 'source', 'track', 'wbr'}


class Sections(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.stack, self.title, self.in_title = [], '', False
        self.sections = [{'id': '', 'title': '', 'text': []}]
        self.heading = None
        self.frameset = False

    def skipping(self):
        return any(s for _, s in self.stack)

    def handle_starttag(self, tag, attrs):
        a = dict(attrs)
        if tag == 'title':
            self.in_title = True
        if tag == 'div' and 'fp-frameset' in (a.get('class') or ''):
            self.frameset = True
        if self.sections and not self.skipping():
            self.sections[-1]['text'].append(' ')  # <br>, <td>, <li>… separate words
        if tag in VOID:
            return
        skip = tag in SKIP_TAGS or bool(SKIP_CLASSES & set((a.get('class') or '').split())) or 'data-fp-noindex' in a
        self.stack.append((tag, skip))
        if tag in ('h1', 'h2', 'h3') and not self.skipping():
            self.sections.append({'id': a.get('id', ''), 'title': '', 'text': []})
            self.heading = tag

    def handle_endtag(self, tag):
        if tag == 'title':
            self.in_title = False
        if tag in VOID:
            return
        while self.stack:
            t, _ = self.stack.pop()
            if t == tag:
                break
        if tag == self.heading:
            self.heading = None

    def handle_data(self, data):
        if self.in_title:
            self.title += data
            return
        if self.skipping():
            return
        cur = self.sections[-1]
        if self.heading:
            cur['title'] += data
        cur['text'].append(data)


def main():
    if '-h' in sys.argv or '--help' in sys.argv:
        print(__doc__)
        return
    argv = sys.argv[1:]
    excluded = set()
    if '--exclude' in argv:
        i = argv.index('--exclude'); excluded = set(argv[i + 1].split(',')); del argv[i:i + 2]
    args = [a for a in argv if not a.startswith('--') and a not in (argv[argv.index('--out') + 1:argv.index('--out') + 2] if '--out' in argv else [])]
    if not args:
        sys.exit(__doc__)
    site = os.path.abspath(args[0])
    out = os.path.join(site, 'theme', 'search-index.js')
    if '--out' in sys.argv:
        out = os.path.join(site, sys.argv[sys.argv.index('--out') + 1])
    entries = []
    for root, _, names in os.walk(site):
        for n in sorted(names):
            if not n.lower().endswith(('.html', '.htm')):
                continue
            path = os.path.join(root, n)
            rel = os.path.relpath(path, site).replace(os.sep, '/')
            p = Sections()
            p.feed(open(path, encoding='utf-8', errors='replace').read())
            if p.frameset or rel in excluded:  # the frameset shell itself is not a result
                continue
            page_title = re.sub(r'\s+', ' ', p.title).strip() or rel
            for s in p.sections:
                text = re.sub(r'\s+', ' ', ''.join(s['text'])).strip()
                if len(text) < 3:
                    continue
                title = re.sub(r'\s+', ' ', s['title']).strip() or page_title
                entries.append({'url': rel + ('#' + s['id'] if s['id'] else ''), 'title': title, 'page': page_title, 'text': text[:4000]})
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, 'w', encoding='utf-8') as f:
        f.write('/* generated by build_search_index.py — re-run after editing pages */\nwindow.FP_SEARCH_INDEX = ')
        json.dump(entries, f, ensure_ascii=False, indent=0)
        f.write(';\n')
    print('indexed %d sections from %s -> %s' % (len(entries), site, out))


if __name__ == '__main__':
    main()
